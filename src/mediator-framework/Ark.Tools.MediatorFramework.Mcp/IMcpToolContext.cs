using Microsoft.Extensions.DependencyInjection;

using System.Text.Json;

namespace Ark.Tools.MediatorFramework.Mcp;

/// <summary>Defines the generated registration contract for an MCP tool context.</summary>
public interface IMcpToolContext
{
    /// <summary>Registers the tools generated for this context.</summary>
    /// <param name="builder">The MCP server builder.</param>
    /// <returns>The supplied builder.</returns>
    static abstract IMcpServerBuilder RegisterMcpTools(IMcpServerBuilder builder);

    /// <summary>Registers the tools generated for this context, serializing their arguments and results with <paramref name="serializerOptions"/>.</summary>
    /// <param name="builder">The MCP server builder.</param>
    /// <param name="serializerOptions">The JSON options for tool arguments and results, typically the options of the HTTP endpoints.</param>
    /// <returns>The supplied builder.</returns>
    /// <remarks>
    /// Generated contexts override this member. The default implementation cannot call
    /// <see cref="RegisterMcpTools(IMcpServerBuilder)"/> of the implementing type, so it throws.
    /// </remarks>
    /// <exception cref="NotSupportedException">The context does not override this member.</exception>
    static virtual IMcpServerBuilder RegisterMcpTools(IMcpServerBuilder builder, JsonSerializerOptions serializerOptions)
    {
        throw new NotSupportedException(
            "This MCP tool context does not support JSON serializer options. Use a context generated by ArkGenerateMcpToolsForAssemblyAttribute.");
    }
}
